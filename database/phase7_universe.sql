-- Phase 7: AI Universe provenance ledger (tables uni_*). Requires Phase 6 (crm_users) to be applied first.
-- ADDITIVE ONLY: every statement is CREATE TABLE IF NOT EXISTS. No existing table is altered, renamed or dropped. Safe to run twice.
-- Do NOT run against a live database before the owner has reviewed it and taken a backup. Rollback: database/phase7_rollback.sql (manual, destructive).
-- Targets MySQL 8.0 / 8.4 and MariaDB 10.11. Collation is explicit (utf8mb4_unicode_ci exists on both. The MySQL 8 default 0900_ai_ci does not exist on MariaDB).
--
-- ONE state vocabulary for every uni_* row: proposed, in_review, verified, rejected, superseded.
-- origin is mandatory: human, ai_assisted or import.
-- Single-row rules are CHECK constraints (enforced by MySQL 8.0.16 and later and by MariaDB 10.2.1 and later):
--   state values, verified needs verified_by + verified_at + review_id, an open row carries no verifier, origin import can never be verified
--   (an imported lead becomes a NEW version with origin human or ai_assisted that a different person verifies), maker is not checker,
--   date precision (month needs day 1, year needs 1 January), source quote not blank, no self-parent, no self-edge.
-- Cross-table rules (at least one source, reviewer holds the verifier role, review matches the target, verified rows immutable, parent date earlier,
--   append-only review and audit tables) cannot be CHECKs. They live in database/phase7_triggers.sql, an OPTIONAL file.
--   PRIMARY ENFORCEMENT IS THE PHP SERVICE LAYER. Triggers are defence in depth. A host that denies CREATE TRIGGER still works
--   with this file alone, but then the service layer is the only guard for those cross-table rules.
-- Foreign keys: ON DELETE RESTRICT and ON UPDATE RESTRICT everywhere. Nothing here cascades. Rows are never hard-deleted: they are superseded.
-- Versioning: lineage_key (VARCHAR(32) because a CHAR base column breaks stored generated columns on MariaDB, app-generated 32 hex) names a logical item. version_no 1 has supersedes_id NULL, later versions point at their predecessor.
--   current_lineage is a STORED generated column that is NULL unless is_current = 1, so UNIQUE (current_lineage) allows only one current version.
--   To publish a correction: supersede the old row (state superseded, is_current 0) BEFORE flipping the new row to is_current 1, in one transaction.
-- Recommended DB grants: the web user gets SELECT, INSERT, UPDATE on uni_* and only SELECT, INSERT on uni_audit_log and uni_review. The importer user INSERT only.
-- Reading rule for every public query: WHERE state = 'verified' AND is_current = 1.

CREATE TABLE IF NOT EXISTS uni_source (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    url VARCHAR(2048) NOT NULL,
    publisher VARCHAR(190) NOT NULL,
    retrieved_at DATETIME NOT NULL,
    quote VARCHAR(1000) NOT NULL,
    content_hash CHAR(64) NULL,
    origin VARCHAR(12) NOT NULL DEFAULT 'human',
    created_by INT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    KEY idx_uni_source_retrieved (retrieved_at),
    KEY idx_uni_source_created_by (created_by),
    CONSTRAINT chk_uni_source_url CHECK (url LIKE 'http://%' OR url LIKE 'https://%'),
    CONSTRAINT chk_uni_source_publisher CHECK (CHAR_LENGTH(TRIM(publisher)) > 0),
    CONSTRAINT chk_uni_source_quote CHECK (CHAR_LENGTH(TRIM(REPLACE(REPLACE(REPLACE(quote, CHAR(9), ''), CHAR(10), ''), CHAR(13), ''))) > 0),
    CONSTRAINT chk_uni_source_origin CHECK (origin IN ('human','ai_assisted','import')),
    CONSTRAINT fk_uni_source_created_by FOREIGN KEY (created_by) REFERENCES crm_users (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

