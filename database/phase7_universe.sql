CREATE TABLE IF NOT EXISTS uni_entity (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    entity_type VARCHAR(12) NOT NULL,
    slug VARCHAR(120) NOT NULL,
    name VARCHAR(190) NOT NULL,
    summary VARCHAR(500) NOT NULL DEFAULT '',
    state VARCHAR(12) NOT NULL DEFAULT 'proposed',
    origin VARCHAR(12) NOT NULL DEFAULT 'human',
    proposed_by INT UNSIGNED NOT NULL,
    proposed_at DATETIME NOT NULL,
    verified_by INT UNSIGNED NULL,
    verified_at DATETIME NULL,
    review_id BIGINT UNSIGNED NULL,
    lineage_key VARCHAR(32) NOT NULL,
    version_no INT UNSIGNED NOT NULL DEFAULT 1,
    supersedes_id BIGINT UNSIGNED NULL,
    is_current TINYINT(1) NOT NULL DEFAULT 1,
    current_lineage VARCHAR(32) GENERATED ALWAYS AS (IF(is_current = 1, lineage_key, NULL)) STORED,
    current_slug VARCHAR(120) GENERATED ALWAYS AS (IF(is_current = 1, slug, NULL)) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uq_uni_entity_current_slug (current_slug),
    KEY idx_uni_entity_type (entity_type, slug),
    UNIQUE KEY uq_uni_entity_current (current_lineage),
    UNIQUE KEY uq_uni_entity_lineage_ver (lineage_key, version_no),
    KEY idx_uni_entity_state (state, is_current),
    KEY idx_uni_entity_proposed_by (proposed_by),
    KEY idx_uni_entity_verified_by (verified_by),
    KEY idx_uni_entity_review (review_id),
    KEY idx_uni_entity_supersedes (supersedes_id),
    CONSTRAINT chk_uni_entity_type CHECK (entity_type IN ('company','product','model','version')),
    CONSTRAINT chk_uni_entity_slug CHECK (CHAR_LENGTH(TRIM(slug)) > 0 AND CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT chk_uni_entity_state CHECK (state IN ('proposed','in_review','verified','rejected','superseded')),
    CONSTRAINT chk_uni_entity_origin CHECK (origin IN ('human','ai_assisted','import')),
    CONSTRAINT chk_uni_entity_verified_fields CHECK (state <> 'verified' OR (verified_by IS NOT NULL AND verified_at IS NOT NULL AND review_id IS NOT NULL)),
    CONSTRAINT chk_uni_entity_open_clean CHECK (state NOT IN ('proposed','in_review') OR (verified_by IS NULL AND verified_at IS NULL)),
    CONSTRAINT chk_uni_entity_import_not_verified CHECK (NOT (origin = 'import' AND state = 'verified')),
    CONSTRAINT chk_uni_entity_maker_checker CHECK (verified_by IS NULL OR verified_by <> proposed_by),
    CONSTRAINT chk_uni_entity_current_flag CHECK (is_current IN (0,1) AND (state NOT IN ('superseded','rejected') OR is_current = 0)),
    CONSTRAINT chk_uni_entity_version CHECK (version_no >= 1 AND ((version_no = 1) = (supersedes_id IS NULL))),
    CONSTRAINT fk_uni_entity_proposed_by FOREIGN KEY (proposed_by) REFERENCES crm_users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_uni_entity_verified_by FOREIGN KEY (verified_by) REFERENCES crm_users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_uni_entity_review FOREIGN KEY (review_id) REFERENCES uni_review (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_uni_entity_supersedes FOREIGN KEY (supersedes_id) REFERENCES uni_entity (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

