CREATE TABLE IF NOT EXISTS uni_edge (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    from_entity_id BIGINT UNSIGNED NOT NULL,
    to_entity_id BIGINT UNSIGNED NOT NULL,
    edge_type VARCHAR(16) NOT NULL,
    valid_from DATE NULL,
    valid_to DATE NULL,
    notes VARCHAR(500) NOT NULL DEFAULT '',
    state VARCHAR(12) NOT NULL DEFAULT 'proposed',
    origin VARCHAR(12) NOT NULL DEFAULT 'human',
    proposed_by INT UNSIGNED NOT NULL,
    proposed_at DATETIME NOT NULL,
    verified_by INT UNSIGNED NULL,
    verified_at DATETIME NULL,
    review_id BIGINT UNSIGNED NULL,
    lineage_key VARCHAR(32) NOT NULL,
    version_no INT UNSIGNED NOT NULL DEFAULT 1,
    supersedes_id BIGINT UNSIGNED NULL,
    is_current TINYINT(1) NOT NULL DEFAULT 1,
    current_lineage VARCHAR(32) GENERATED ALWAYS AS (IF(is_current = 1, lineage_key, NULL)) STORED,
    current_edge VARCHAR(64) GENERATED ALWAYS AS (IF(is_current = 1 AND state <> 'rejected', CONCAT(from_entity_id, ':', to_entity_id, ':', edge_type), NULL)) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uq_uni_edge_current_triple (current_edge),
    KEY idx_uni_edge_from (from_entity_id, edge_type),
    KEY idx_uni_edge_to (to_entity_id, edge_type),
    UNIQUE KEY uq_uni_edge_current (current_lineage),
    UNIQUE KEY uq_uni_edge_lineage_ver (lineage_key, version_no),
    KEY idx_uni_edge_state (state, is_current),
    KEY idx_uni_edge_proposed_by (proposed_by),
    KEY idx_uni_edge_verified_by (verified_by),
    KEY idx_uni_edge_review (review_id),
    KEY idx_uni_edge_supersedes (supersedes_id),
    CONSTRAINT chk_uni_edge_type CHECK (edge_type IN ('developed_by','version_of','derived_from','successor_of','renamed_from','acquired_by','integrates_with','built_on','hosted_on')),
    CONSTRAINT chk_uni_edge_no_self CHECK (from_entity_id <> to_entity_id),
    CONSTRAINT chk_uni_edge_validity CHECK (valid_from IS NULL OR valid_to IS NULL OR valid_to >= valid_from),
    CONSTRAINT chk_uni_edge_state CHECK (state IN ('proposed','in_review','verified','rejected','superseded')),
    CONSTRAINT chk_uni_edge_origin CHECK (origin IN ('human','ai_assisted','import')),
    CONSTRAINT chk_uni_edge_verified_fields CHECK (state <> 'verified' OR (verified_by IS NOT NULL AND verified_at IS NOT NULL AND review_id IS NOT NULL)),
    CONSTRAINT chk_uni_edge_open_clean CHECK (state NOT IN ('proposed','in_review') OR (verified_by IS NULL AND verified_at IS NULL)),
    CONSTRAINT chk_uni_edge_import_not_verified CHECK (NOT (origin = 'import' AND state = 'verified')),
    CONSTRAINT chk_uni_edge_maker_checker CHECK (verified_by IS NULL OR verified_by <> proposed_by),
    CONSTRAINT chk_uni_edge_current_flag CHECK (is_current IN (0,1) AND (state NOT IN ('superseded','rejected') OR is_current = 0)),
    CONSTRAINT chk_uni_edge_version CHECK (version_no >= 1 AND ((version_no = 1) = (supersedes_id IS NULL))),
    CONSTRAINT fk_uni_edge_from FOREIGN KEY (from_entity_id) REFERENCES uni_entity (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_uni_edge_to FOREIGN KEY (to_entity_id) REFERENCES uni_entity (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_uni_edge_proposed_by FOREIGN KEY (proposed_by) REFERENCES crm_users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
